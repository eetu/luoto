//! The UI's TypeScript types (`frontend/src/lib/generated/api.ts`), generated from the Rust
//! types the UI API sends and takes: what its handlers' signatures name, and what they follow.
//! `just types` writes the file; this test fails while the committed one differs, so a change
//! to an API type the frontend doesn't follow fails its typecheck or this test.
//!
//! It reads the source with syn and applies serde's attributes as serde does. An attribute, a
//! type or a path it doesn't know fails the test rather than produce a wrong type.

use std::collections::{BTreeMap, HashMap};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use syn::ext::IdentExt;
use syn::{
    Attribute, Expr, Fields, FieldsNamed, FnArg, GenericArgument, Item, Lit, PathArguments,
    ReturnType, Type, UseTree,
};

const OUT: &str = "../frontend/src/lib/generated/api.ts";

/// The module whose handlers are the API.
const API: &str = "luoto::ui::api";

/// Types the API sends that its handlers' signatures don't name.
const EXTRA: &[&str] = &[
    // Every line of `/api/stream`.
    "luoto_shared::events::Event",
    // `POST /api/envs/{name}/selftest` and `POST /api/vault/reload`, sent as a `Value`.
    "luoto::env::SelftestReport",
    "luoto::sync::Reloaded",
];

/// TypeScript names for Rust names that say too little outside their module.
const RENAME: &[(&str, &str)] = &[
    ("luoto_shared::events::Event", "LuotoEvent"),
    ("luoto::repos::Listed", "Repo"),
    ("luoto::repos::Origin", "RepoOrigin"),
    ("luoto::project::Status", "ProjectStatus"),
    ("luoto::project::State", "ProjectState"),
];

/// The line width of the frontend's code (`.editorconfig`), within which a union stays on
/// one line.
const WIDTH: usize = 100;

const HEADER: &str = "// Generated by `just types` (cli/tests/api_types.rs) from the Rust types luoto's UI API\n\
                      // sends and takes. Change those, not this file.\n";

#[test]
fn frontend_types_match_the_rust_api() {
    let text = generate();
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join(OUT);
    if std::env::var_os("LUOTO_WRITE_TYPES").is_some() {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, &text).unwrap();
        return;
    }
    let committed = std::fs::read_to_string(&path)
        .unwrap_or_default()
        .replace("\r\n", "\n");
    if committed != text {
        let (line, (want, got)) = text
            .lines()
            .chain(std::iter::repeat(""))
            .zip(committed.lines().chain(std::iter::repeat("")))
            .enumerate()
            .find(|(_, (a, b))| a != b)
            .unwrap();
        panic!(
            "{OUT} differs from the Rust API types; run `just types`.\n\
             line {}:\n  generated: {want}\n  committed: {got}",
            line + 1
        );
    }
}

fn generate() -> String {
    let mut g = Gen::default();
    let api = g.module(API);
    for item in &api.fns {
        if let ReturnType::Type(_, ty) = &item.sig.output
            && let Some(t) = wrapped(ty, &["ApiResult", "Json"])
        {
            g.ts(API, t);
        }
        for arg in &item.sig.inputs {
            if let FnArg::Typed(p) = arg
                && let Some(t) = wrapped(&p.ty, &["Json"])
            {
                g.ts(API, t);
            }
        }
    }
    for path in EXTRA {
        g.named(path);
    }
    while let Some(full) = g.queue.pop() {
        let decl = g.decl(&full);
        g.out.insert(ts_name(&full).to_string(), decl);
    }
    let mut text = HEADER.to_string();
    for decl in g.out.values() {
        text.push('\n');
        text.push_str(decl);
    }
    text
}

/// `T` of `Wrapper<T>`, for a wrapper among `names`.
fn wrapped<'a>(ty: &'a Type, names: &[&str]) -> Option<&'a Type> {
    let Type::Path(p) = ty else { return None };
    let last = p.path.segments.last()?;
    if !names.contains(&last.ident.to_string().as_str()) {
        return None;
    }
    type_args(&last.arguments).into_iter().next()
}

fn type_args(args: &PathArguments) -> Vec<&Type> {
    match args {
        PathArguments::AngleBracketed(a) => a
            .args
            .iter()
            .filter_map(|a| match a {
                GenericArgument::Type(t) => Some(t),
                _ => None,
            })
            .collect(),
        _ => Vec::new(),
    }
}

fn ts_name(full: &str) -> &str {
    RENAME
        .iter()
        .find(|(rust, _)| *rust == full)
        .map_or_else(|| full.rsplit("::").next().unwrap(), |&(_, ts)| ts)
}

/// A parsed source file: its `use`s and its types.
struct Module {
    uses: HashMap<String, String>,
    items: HashMap<String, Item>,
    fns: Vec<syn::ItemFn>,
}

#[derive(Default)]
struct Gen {
    modules: HashMap<String, std::rc::Rc<Module>>,
    /// Full Rust path of every type named so far, by its TypeScript name.
    names: HashMap<String, String>,
    queue: Vec<String>,
    out: BTreeMap<String, String>,
}

/// Which way a type crosses the API, from what it derives.
#[derive(Clone, Copy, PartialEq)]
enum Dir {
    /// Sent by the API (it derives `Serialize`): the JSON serde writes.
    Out,
    /// Only received (`Deserialize` alone): what serde accepts.
    In,
}

impl Gen {
    fn module(&mut self, path: &str) -> std::rc::Rc<Module> {
        if let Some(m) = self.modules.get(path) {
            return m.clone();
        }
        let mut segs = path.split("::");
        let base = match segs.next() {
            Some("luoto") => "src",
            Some("luoto_shared") => "../shared/src",
            _ => panic!("`{path}` is not a module of luoto or luoto-shared"),
        };
        let rel: PathBuf = segs.collect();
        let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join(base);
        let candidates = if rel.as_os_str().is_empty() {
            [dir.join("main.rs"), dir.join("lib.rs")]
        } else {
            [
                dir.join(&rel).with_extension("rs"),
                dir.join(&rel).join("mod.rs"),
            ]
        };
        let file = candidates
            .into_iter()
            .find(|f| f.is_file())
            .unwrap_or_else(|| panic!("no source file for module `{path}`"));
        let src = std::fs::read_to_string(&file)
            .unwrap()
            .replace("\r\n", "\n");
        let parsed = syn::parse_file(&src).unwrap_or_else(|e| panic!("{}: {e}", file.display()));
        let mut m = Module {
            uses: HashMap::new(),
            items: HashMap::new(),
            fns: Vec::new(),
        };
        for item in parsed.items {
            let ident = match &item {
                Item::Struct(s) => s.ident.to_string(),
                Item::Enum(e) => e.ident.to_string(),
                Item::Use(u) => {
                    flatten_use(path, &mut Vec::new(), &u.tree, &mut m.uses);
                    continue;
                }
                Item::Fn(f) => {
                    m.fns.push(f.clone());
                    continue;
                }
                _ => continue,
            };
            m.items.insert(ident, item);
        }
        let m = std::rc::Rc::new(m);
        self.modules.insert(path.to_string(), m.clone());
        m
    }

    /// The full path `path` names in module `m`.
    fn resolve(&mut self, m: &str, path: &syn::Path) -> String {
        let segs: Vec<String> = path
            .segments
            .iter()
            .map(|s| s.ident.unraw().to_string())
            .collect();
        let head = match segs[0].as_str() {
            "crate" | "super" | "self" => absolute(m, &segs[0]),
            first => match self.module(m).uses.get(first) {
                Some(full) => full.clone(),
                None if segs.len() == 1 => format!("{m}::{first}"),
                None => first.to_string(),
            },
        };
        std::iter::once(head)
            .chain(segs[1..].iter().cloned())
            .collect::<Vec<_>>()
            .join("::")
    }

    /// The TypeScript for `ty`, written in module `m`; queues the types it names.
    fn ts(&mut self, m: &str, ty: &Type) -> String {
        match ty {
            Type::Reference(r) => self.ts(m, &r.elem),
            Type::Paren(p) => self.ts(m, &p.elem),
            Type::Slice(s) => array(&self.ts(m, &s.elem)),
            Type::Array(a) => array(&self.ts(m, &a.elem)),
            Type::Tuple(t) if t.elems.is_empty() => "null".into(),
            Type::Tuple(t) => {
                let elems: Vec<String> = t.elems.iter().map(|e| self.ts(m, e)).collect();
                format!("[{}]", elems.join(", "))
            }
            Type::Path(p) if p.qself.is_none() => self.ts_path(m, &p.path),
            _ => panic!("{m}: a type with no TypeScript form (a function, trait or macro)"),
        }
    }

    fn ts_path(&mut self, m: &str, path: &syn::Path) -> String {
        let last = path.segments.last().unwrap();
        let ident = last.ident.to_string();
        let local = path.segments.len() == 1 && !self.module(m).uses.contains_key(&ident);
        let full = if local && PRELUDE.contains(&ident.as_str()) {
            ident.clone()
        } else {
            self.resolve(m, path)
        };
        let krate = full.split("::").next().unwrap();
        if !(full == ident || ["std", "core", "alloc", "chrono", "serde_json"].contains(&krate)) {
            return self.named(&full);
        }
        let args = type_args(&last.arguments);
        let mut arg = |i: usize| {
            let t = args
                .get(i)
                .unwrap_or_else(|| panic!("{m}: `{full}` without its type arguments"));
            self.ts(m, t)
        };
        match ident.as_str() {
            "String" | "str" | "char" | "PathBuf" | "DateTime" => "string".into(),
            "bool" => "boolean".into(),
            "u8" | "u16" | "u32" | "u64" | "usize" | "i8" | "i16" | "i32" | "i64" | "isize"
            | "f32" | "f64" => "number".into(),
            "Option" => format!("{} | null", arg(0)),
            "Vec" | "VecDeque" | "BTreeSet" | "HashSet" => array(&arg(0)),
            "BTreeMap" | "HashMap" => match (arg(0).as_str(), arg(1)) {
                ("string", v) => format!("Record<string, {v}>"),
                (k, _) => panic!("{m}: a map keyed by `{k}`"),
            },
            "Box" | "Arc" | "Rc" => arg(0),
            "Value" if full == "serde_json::Value" => "unknown".into(),
            _ => panic!("{m}: no TypeScript for `{full}`"),
        }
    }

    /// The TypeScript name of the type at `full`, queued for its declaration.
    fn named(&mut self, full: &str) -> String {
        let name = ts_name(full).to_string();
        match self.names.get(&name) {
            Some(seen) if seen == full => {}
            Some(seen) => panic!("`{seen}` and `{full}` are both `{name}`: add one to RENAME"),
            None => {
                self.names.insert(name.clone(), full.to_string());
                self.queue.push(full.to_string());
            }
        }
        name
    }

    /// `export type …` for the type at `full`.
    fn decl(&mut self, full: &str) -> String {
        let (m, ident) = full.rsplit_once("::").unwrap();
        let module = self.module(m);
        let Some(item) = module.items.get(ident) else {
            if let Some(target) = module.uses.get(ident) {
                return self.decl(target);
            }
            panic!("no struct or enum `{full}`");
        };
        let (attrs, generics) = match item {
            Item::Struct(s) => (&s.attrs, &s.generics),
            Item::Enum(e) => (&e.attrs, &e.generics),
            _ => unreachable!(),
        };
        if !generics.params.is_empty() {
            panic!("`{full}` is generic");
        }
        let derives = derives(attrs);
        let dir = match (
            derives.iter().any(|d| d == "Serialize"),
            derives.iter().any(|d| d == "Deserialize"),
        ) {
            (true, _) => Dir::Out,
            (false, true) => Dir::In,
            _ => panic!("`{full}` derives neither Serialize nor Deserialize"),
        };
        let serde = serde_attrs(full, attrs);
        let name = ts_name(full);
        let mut text = jsdoc(&docs(attrs), "");
        let body = match item {
            Item::Struct(s) => {
                for (key, _) in &serde {
                    if !["rename_all", "default", "deny_unknown_fields"].contains(&key.as_str()) {
                        panic!("`{full}`: serde `{key}` is not supported on a struct");
                    }
                }
                let case = value(&serde, "rename_all");
                let defaults = serde.iter().any(|(k, _)| k == "default");
                match &s.fields {
                    Fields::Named(f) => {
                        let (fields, flat) = self.fields(m, f, case, dir, defaults);
                        let mut body = String::from("{\n");
                        for f in fields {
                            body.push_str(&jsdoc(&f.docs, "  "));
                            let opt = if f.optional { "?" } else { "" };
                            writeln!(body, "  {}{opt}: {};", f.name, f.ty).unwrap();
                        }
                        body.push('}');
                        for t in flat {
                            write!(body, " & {t}").unwrap();
                        }
                        body
                    }
                    Fields::Unnamed(f) if f.unnamed.len() == 1 => self.ts(m, &f.unnamed[0].ty),
                    Fields::Unnamed(f) => {
                        let elems: Vec<String> =
                            f.unnamed.iter().map(|f| self.ts(m, &f.ty)).collect();
                        format!("[{}]", elems.join(", "))
                    }
                    Fields::Unit => "null".into(),
                }
            }
            Item::Enum(e) => self.enum_body(full, m, e, &serde, dir),
            _ => unreachable!(),
        };
        let sep = if body.starts_with('\n') { "" } else { " " };
        writeln!(text, "export type {name} ={sep}{body};").unwrap();
        text
    }

    fn enum_body(
        &mut self,
        full: &str,
        m: &str,
        e: &syn::ItemEnum,
        serde: &[(String, Option<String>)],
        dir: Dir,
    ) -> String {
        for (key, _) in serde {
            if !["rename_all", "tag", "untagged"].contains(&key.as_str()) {
                panic!("`{full}`: serde `{key}` is not supported on an enum");
            }
        }
        let case = value(serde, "rename_all");
        let tag = value(serde, "tag");
        let untagged = serde.iter().any(|(k, _)| k == "untagged");
        let mut members: Vec<(Vec<String>, String)> = Vec::new();
        for v in &e.variants {
            let vserde = serde_attrs(full, &v.attrs);
            let mut name = rename(case, &v.ident.unraw().to_string(), true);
            for (key, val) in &vserde {
                match key.as_str() {
                    "rename" => name = val.clone().unwrap(),
                    _ => panic!("`{full}::{}`: serde `{key}` is not supported", v.ident),
                }
            }
            let lit = format!("\"{name}\"");
            let ty = match (&v.fields, tag, untagged) {
                (Fields::Unit, _, true) => "null".into(),
                (Fields::Unit, Some(t), _) => format!("{{ {t}: {lit} }}"),
                (Fields::Unit, None, _) => lit,
                (Fields::Named(f), _, _) => {
                    let (fields, flat) = self.fields(m, f, None, dir, false);
                    if !flat.is_empty() {
                        panic!("`{full}::{}`: flatten in a variant", v.ident);
                    }
                    let mut members: Vec<String> = tag
                        .filter(|_| !untagged)
                        .map(|t| format!("{t}: {lit}"))
                        .into_iter()
                        .collect();
                    members.extend(fields.iter().map(|f| {
                        let opt = if f.optional { "?" } else { "" };
                        format!("{}{opt}: {}", f.name, f.ty)
                    }));
                    let obj = format!("{{ {} }}", members.join("; "));
                    match (tag, untagged) {
                        (None, false) => format!("{{ {name}: {obj} }}"),
                        _ => obj,
                    }
                }
                (Fields::Unnamed(f), _, _) => {
                    let elems: Vec<String> = f.unnamed.iter().map(|f| self.ts(m, &f.ty)).collect();
                    let inner = if elems.len() == 1 {
                        elems[0].clone()
                    } else {
                        format!("[{}]", elems.join(", "))
                    };
                    match (tag, untagged) {
                        (_, true) => inner,
                        (Some(t), _) if elems.len() == 1 => format!("{{ {t}: {lit} }} & {inner}"),
                        (Some(_), _) => panic!("`{full}::{}`: a tagged tuple variant", v.ident),
                        (None, _) => format!("{{ {name}: {inner} }}"),
                    }
                }
            };
            members.push((docs(&v.attrs), ty));
        }
        let one_line = members
            .iter()
            .map(|(_, t)| t.as_str())
            .collect::<Vec<_>>()
            .join(" | ");
        let width = format!("export type {} = {one_line};", ts_name(full)).len();
        if members.iter().all(|(d, _)| d.is_empty()) && width <= WIDTH {
            return one_line;
        }
        let mut body = String::new();
        for (docs, ty) in members {
            body.push('\n');
            body.push_str(jsdoc(&docs, "  ").trim_end_matches('\n'));
            if !docs.is_empty() {
                body.push('\n');
            }
            write!(body, "  | {ty}").unwrap();
        }
        body
    }

    /// The fields serde writes (`Dir::Out`) or accepts (`Dir::In`), and the types flattened
    /// into them.
    fn fields(
        &mut self,
        m: &str,
        fields: &FieldsNamed,
        case: Option<&str>,
        dir: Dir,
        defaults: bool,
    ) -> (Vec<Field>, Vec<String>) {
        let mut out = Vec::new();
        let mut flat = Vec::new();
        for f in &fields.named {
            let ident = f.ident.as_ref().unwrap().unraw().to_string();
            let serde = serde_attrs(&format!("{m}: field `{ident}`"), &f.attrs);
            let (mut name, mut default, mut skip_if, mut flatten) =
                (rename(case, &ident, false), defaults, None, false);
            let mut skip = false;
            for (key, val) in serde {
                match key.as_str() {
                    "skip" => skip = true,
                    "rename" => name = val.unwrap(),
                    "default" => default = true,
                    "skip_serializing_if" => skip_if = val,
                    "flatten" => flatten = true,
                    _ => panic!("{m}: field `{ident}`: serde `{key}` is not supported"),
                }
            }
            if skip {
                continue;
            }
            if flatten {
                flat.push(self.ts(m, &f.ty));
                continue;
            }
            let option = wrapped(&f.ty, &["Option"]);
            let (optional, ty) = match dir {
                Dir::Out => match (skip_if.as_deref(), option) {
                    (Some("Option::is_none"), Some(inner)) => (true, self.ts(m, inner)),
                    (Some(_), _) => (true, self.ts(m, &f.ty)),
                    (None, _) => (false, self.ts(m, &f.ty)),
                },
                Dir::In => (default || option.is_some(), self.ts(m, &f.ty)),
            };
            out.push(Field {
                docs: docs(&f.attrs),
                name,
                optional,
                ty,
            });
        }
        (out, flat)
    }
}

struct Field {
    docs: Vec<String>,
    name: String,
    optional: bool,
    ty: String,
}

/// Types used without a `use`.
const PRELUDE: &[&str] = &[
    "String", "str", "char", "bool", "u8", "u16", "u32", "u64", "usize", "i8", "i16", "i32", "i64",
    "isize", "f32", "f64", "Option", "Vec", "Box",
];

/// `crate`, `super` or `self` in module `m`, as a full path.
fn absolute(m: &str, head: &str) -> String {
    match head {
        "crate" => m.split("::").next().unwrap().to_string(),
        "super" => m.rsplit_once("::").map(|(p, _)| p.to_string()).unwrap(),
        _ => m.to_string(),
    }
}

/// Each name a `use` brings into module `m`, with the full path it stands for.
fn flatten_use(
    m: &str,
    prefix: &mut Vec<String>,
    tree: &UseTree,
    out: &mut HashMap<String, String>,
) {
    let full = |prefix: &[String], last: Option<String>| {
        let mut segs: Vec<String> = prefix.iter().cloned().chain(last).collect();
        if matches!(segs[0].as_str(), "crate" | "super" | "self") {
            segs[0] = absolute(m, &segs[0]);
        }
        segs.join("::")
    };
    match tree {
        UseTree::Path(p) => {
            prefix.push(p.ident.to_string());
            flatten_use(m, prefix, &p.tree, out);
            prefix.pop();
        }
        UseTree::Name(n) if n.ident == "self" => {
            out.insert(prefix.last().unwrap().clone(), full(prefix, None));
        }
        UseTree::Name(n) => {
            out.insert(n.ident.to_string(), full(prefix, Some(n.ident.to_string())));
        }
        UseTree::Rename(r) => {
            let last = (r.ident != "self").then(|| r.ident.to_string());
            out.insert(r.rename.to_string(), full(prefix, last));
        }
        UseTree::Glob(_) => {}
        UseTree::Group(g) => {
            for t in &g.items {
                flatten_use(m, prefix, t, out);
            }
        }
    }
}

fn derives(attrs: &[Attribute]) -> Vec<String> {
    let mut out = Vec::new();
    for a in attrs.iter().filter(|a| a.path().is_ident("derive")) {
        a.parse_nested_meta(|meta| {
            out.push(meta.path.segments.last().unwrap().ident.to_string());
            Ok(())
        })
        .unwrap();
    }
    out
}

/// Every `#[serde(key)]` and `#[serde(key = "value")]`.
fn serde_attrs(what: &str, attrs: &[Attribute]) -> Vec<(String, Option<String>)> {
    let mut out = Vec::new();
    for a in attrs.iter().filter(|a| a.path().is_ident("serde")) {
        a.parse_nested_meta(|meta| {
            let key = meta.path.get_ident().map(|i| i.to_string());
            let key = key.unwrap_or_else(|| panic!("{what}: a serde attribute that isn't a name"));
            let value = if meta.input.peek(syn::Token![=]) {
                match meta.value()?.parse::<Lit>()? {
                    Lit::Str(s) => Some(s.value()),
                    _ => panic!("{what}: serde `{key}` without a string"),
                }
            } else {
                None
            };
            out.push((key, value));
            Ok(())
        })
        .unwrap_or_else(|e| panic!("{what}: {e}"));
    }
    out
}

fn value<'a>(serde: &'a [(String, Option<String>)], key: &str) -> Option<&'a str> {
    serde
        .iter()
        .find(|(k, _)| k == key)
        .and_then(|(_, v)| v.as_deref())
}

/// serde's `rename_all` for a variant or field name.
fn rename(case: Option<&str>, ident: &str, variant: bool) -> String {
    let snake = || {
        let mut s = String::new();
        for (i, c) in ident.chars().enumerate() {
            if c.is_uppercase() && i > 0 {
                s.push('_');
            }
            s.push(c.to_ascii_lowercase());
        }
        s
    };
    match case {
        None => ident.to_string(),
        Some("lowercase") => ident.to_ascii_lowercase(),
        Some("snake_case") if variant => snake(),
        Some("snake_case") => ident.to_string(),
        Some("kebab-case") if variant => snake().replace('_', "-"),
        Some("kebab-case") => ident.replace('_', "-"),
        Some(other) => panic!("rename_all = \"{other}\" is not supported"),
    }
}

fn docs(attrs: &[Attribute]) -> Vec<String> {
    attrs
        .iter()
        .filter(|a| a.path().is_ident("doc"))
        .filter_map(|a| match &a.meta {
            syn::Meta::NameValue(nv) => match &nv.value {
                Expr::Lit(syn::ExprLit {
                    lit: Lit::Str(s), ..
                }) => Some(s.value()),
                _ => None,
            },
            _ => None,
        })
        .flat_map(|s| {
            s.lines()
                .map(|l| l.strip_prefix(' ').unwrap_or(l).trim_end().to_string())
                .collect::<Vec<_>>()
        })
        .collect()
}

fn jsdoc(lines: &[String], indent: &str) -> String {
    let lines: Vec<String> = lines.iter().map(|l| l.replace("*/", "*\\/")).collect();
    match lines.as_slice() {
        [] => String::new(),
        [one] => format!("{indent}/** {one} */\n"),
        many => {
            let mut s = format!("{indent}/**\n");
            for l in many {
                if l.is_empty() {
                    writeln!(s, "{indent} *").unwrap();
                } else {
                    writeln!(s, "{indent} * {l}").unwrap();
                }
            }
            writeln!(s, "{indent} */").unwrap();
            s
        }
    }
}

/// `T[]`, parenthesized when `T` is a union or an intersection.
fn array(t: &str) -> String {
    let mut depth = 0i32;
    let mut compound = false;
    for c in t.chars() {
        match c {
            '[' | '{' | '<' | '(' => depth += 1,
            ']' | '}' | '>' | ')' => depth -= 1,
            '|' | '&' if depth == 0 => compound = true,
            _ => {}
        }
    }
    if compound {
        format!("({t})[]")
    } else {
        format!("{t}[]")
    }
}
